export const normalizeChapterText = (str) => {
  if (!str) return '';
  return str
    .replace(/[০-৯0-9]/g, '')
    .replace(/অধ্যায়|অধ্যায়|Chapter|Part|পর্ব|অঙ্ক|গদ্য|পদ্য|সহপাঠ|ব্যাকরণ|নির্মিতি|Unit/gi, '')
    .replace(/[।.,:—–\-‘'"`“”()]/g, '')
    .replace(/\s+/g, '')
    .toLowerCase();
};

export const findCuratedQuizForChapter = (subId, chapter) => {
  if (!chapter) return null;
  const list = NCTB_10Q_CHAPTER_QUIZZES[subId] || [];
  const chClean = normalizeChapterText(chapter.title || chapter.chapterNameBn || '');

  // 1. Direct ID match
  const byId = list.find(c => c.chapterId === chapter.id || c.chapterId === chapter.chapterId);
  if (byId) return byId;

  // 2. Normalized Title match
  return list.find(c => {
    const curatedClean = normalizeChapterText(c.chapterNameBn || c.chapterNameEn || '');
    return (
      (chClean.length > 2 && curatedClean.includes(chClean)) ||
      (curatedClean.length > 2 && chClean.includes(curatedClean))
    );
  }) || null;
};
